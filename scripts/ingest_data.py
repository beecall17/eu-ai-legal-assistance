# Document validation
# ---------------------------------------------------------------------------

def validate_child_documents(
    documents: List[Document],
) -> None:
    """Validate chunk IDs and required metadata."""

    if not documents:
        raise RuntimeError(
            "No child documents were generated."
        )

    required_metadata = {
        "source",
        "source_sha256",
        "document",
        "document_title",
        "legal_version",
        "section_type",
        "section_number",
        "section_id",
        "parent_id",
        "chunk_id",
        "chunk_index",
        "content_sha256",
        "page_start",
        "page_end",
    }

    ids = set()

    for index, document in enumerate(
        documents
    ):
        metadata = document.metadata

        missing = (
            required_metadata
            - set(metadata.keys())
        )

        if missing:
            raise RuntimeError(
                f"Chunk {index} is missing metadata: "
                f"{sorted(missing)}"
            )

        chunk_id = metadata[
            "chunk_id"
        ]

        if chunk_id in ids:
            raise RuntimeError(
                f"Duplicate chunk ID detected: "
                f"{chunk_id}"
            )

        ids.add(chunk_id)

        if not document.page_content.strip():
            raise RuntimeError(
                f"Chunk {index} contains empty text."
            )

        if metadata.get("chunking_strategy") != "legal_structure_v2":
            raise RuntimeError(
                f"Chunk {index} has an unexpected chunking strategy."
            )

    print(
        f"   ✅ Validated {len(documents):,} "
        "child chunks."
    )


