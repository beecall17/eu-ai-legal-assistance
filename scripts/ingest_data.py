def normalize_whitespace(text: str) -> str:
    """Normalize whitespace while preserving paragraph boundaries."""

    if not text:
        return ""

    text = text.replace(
        "\r\n",
        "\n",
    ).replace(
        "\r",
        "\n",
    )

    text = re.sub(
        r"[ \t]+\n",
        "\n",
        text,
    )

    text = re.sub(
        r"[ \t]{2,}",
        " ",
        text,
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    return text.strip()


def clean_pdf_text(text: str) -> str:
    """
    Clean common PDF extraction artifacts.

    The cleaning is intentionally conservative because this is legal text.
    """

    if not text:
        return ""

    # Remove Markdown heading markers generated by PyMuPDF4LLM.
    text = re.sub(
        r"^\s*#{1,6}\s*",
        "",
        text,
        flags=re.MULTILINE,
    )

    # Remove Markdown emphasis markers.
    text = text.replace(
        "**",
        "",
    )

    text = text.replace(
        "__",
        "",
    )

    # Remove page counters such as:
    #
    #     43/144
    #
    text = re.sub(
        r"^\s*\d+\s*/\s*\d+\s*$",
        "",
        text,
        flags=re.MULTILINE,
    )

    # Remove standalone language markers.
    text = re.sub(
        r"^\s*EN\s*$",
        "",
        text,
        flags=re.MULTILINE | re.IGNORECASE,
    )

    # Remove Official Journal metadata lines.
    text = re.sub(
        r"^\s*OJ\s+L,.*$",
        "",
        text,
        flags=re.MULTILINE | re.IGNORECASE,
    )

    text = re.sub(
        r"^\s*Text with EEA relevance\s*$",
        "",
        text,
        flags=re.MULTILINE | re.IGNORECASE,
    )

    # Remove repeated Official Journal header lines while preserving
    # the first occurrence if one exists.
    lines = text.splitlines()

    seen_oj_header = False
    cleaned_lines: List[str] = []

    for line in lines:
        normalized = line.strip().lower()

        if (
            normalized
            == "official journal of the european union"
        ):
            if seen_oj_header:
                continue

            seen_oj_header = True

        cleaned_lines.append(line)

    return normalize_whitespace(
        "\n".join(cleaned_lines)
    )


def sha256_file(
    file_path: Path,
) -> str:
    """Calculate SHA-256 for the source PDF."""

    digest = hashlib.sha256()

    with file_path.open(
        "rb"
    ) as file:
        for block in iter(
            lambda: file.read(1024 * 1024),
            b"",
        ):
            digest.update(block)

    return digest.hexdigest()


def roman_to_int(value: str) -> int:
    """Convert a valid Roman numeral to an integer."""

    values = {
        "I": 1,
        "V": 5,
        "X": 10,
        "L": 50,
        "C": 100,
        "D": 500,
        "M": 1000,
    }

    value = value.upper().strip()

    if not value:
        raise ValueError(
            "Roman numeral cannot be empty."
        )

    if not re.fullmatch(
        r"[IVXLCDM]+",
        value,
    ):
        raise ValueError(
            f"Invalid Roman numeral: {value!r}"
        )

    total = 0
    previous = 0

    for char in reversed(value):
        current = values[char]

        if current < previous:
            total -= current
        else:
            total += current

        previous = current

    return total


